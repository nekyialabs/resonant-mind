// Plain, reviewable PostgreSQL for putting the set-aside data that v4 has a home for back after the import:
// observation_sits, observations.last_sat_at and images.charge / view_count / last_viewed_at. It is text. Nothing in
// the migrator runs it: the owner reads it, and runs it (or does not) in psql against the v4 target.
//
// Quoting: standard SQL string literals with the quote doubled, and no E-strings, so the script needs
// standard_conforming_strings = on (the default; the script sets it for its own transaction). Timestamps are written
// as explicit UTC (`TIMESTAMPTZ '2026-05-20 08:00:00+00'`), never in the session's TimeZone. A value that cannot be
// written with certainty is left out and listed under NOT RESTORED, never guessed.

const NAIVE = /^\d{4}-\d\d-\d\d[ T]\d\d:\d\d:\d\d(?:\.\d{1,9})?$/u;
const WITH_OFFSET = /^\d{4}-\d\d-\d\d[ T]\d\d:\d\d:\d\d(?:\.\d{1,9})?(?:Z|[+-]\d\d(?::?\d\d)?)$/u;

function literal(value) {
  if (typeof value !== 'string' || value.includes('\u0000')) return null;
  return `'${value.replaceAll("'", "''")}'`;
}

function integer(value) {
  if (typeof value === 'number' && Number.isSafeInteger(value)) return String(value);
  if (value !== null && typeof value === 'object' && typeof value.$integer === 'string' && /^-?\d+$/u.test(value.$integer)) return value.$integer;
  return null;
}

// SQLite's own datetime('now') text is UTC without a zone; a value that carries its own offset keeps it.
function timestamp(value) {
  if (typeof value !== 'string') return null;
  if (NAIVE.test(value)) return `TIMESTAMPTZ '${value.replace('T', ' ')}+00'`;
  if (WITH_OFFSET.test(value)) return `TIMESTAMPTZ '${value.replace('T', ' ')}'`;
  return null;
}

const NULL = 'NULL';
const orNull = (value, convert) => (value === undefined || value === null ? NULL : convert(value));

function rowsOf(section) {
  return Array.isArray(section?.rows) ? section.rows : [];
}

function valuesBlock(rows) {
  return rows.map((row) => `  (${row.join(', ')})`).join(',\n');
}

/**
 * @param {object} setAside the parsed set-aside document (format rmig-set-aside/1)
 * @returns {{ sql: string|null, counts: object, not_restored: object[] }} sql is null when there is nothing to restore
 */
export function buildRestoreSql(setAside) {
  const notRestored = [];
  const skip = (section, key, reason) => notRestored.push({ section, key, reason });

  const sits = [];
  for (const row of rowsOf(setAside.tables?.observation_sits)) {
    const id = integer(row.id);
    const observation = integer(row.observation_id);
    const note = orNull(row.sit_note, literal);
    const at = orNull(row.sat_at, timestamp);
    if (id === null || observation === null || note === null || at === null) { skip('observation_sits', { id: row.id ?? null }, 'a value is missing, not the expected type or not a recognised UTC/offset time'); continue; }
    sits.push([id, observation, note, at]);
  }

  const lastSat = [];
  for (const row of rowsOf(setAside.columns?.observations)) {
    if (row.values?.last_sat_at === undefined) continue;
    const id = integer(row.key?.id);
    const at = timestamp(row.values.last_sat_at);
    if (id === null || at === null) { skip('observations.last_sat_at', row.key ?? null, 'the id or the time is not in a recognised form'); continue; }
    lastSat.push([id, at]);
  }

  const images = [];
  for (const row of rowsOf(setAside.columns?.images)) {
    const values = row.values ?? {};
    if (values.charge === undefined && values.view_count === undefined && values.last_viewed_at === undefined) continue;
    const id = integer(row.key?.id);
    const charge = orNull(values.charge, literal);
    const views = orNull(values.view_count, integer);
    const viewedAt = orNull(values.last_viewed_at, timestamp);
    if (id === null || charge === null || views === null || viewedAt === null) { skip('images', row.key ?? null, 'a value is not the expected type or not a recognised UTC/offset time'); continue; }
    images.push([id, charge, views, viewedAt]);
  }

  const counts = { observation_sits: sits.length, observations_last_sat_at: lastSat.length, images: images.length, not_restored: notRestored.length };
  if (sits.length + lastSat.length + images.length === 0 && notRestored.length === 0) return { sql: null, counts, not_restored: notRestored };

  const out = [
    '-- Restore of set-aside data that v4 has a home for. Generated by normalise-source from set-aside.json.',
    '-- It is plain SQL for you to read: nothing in the migrator runs it. Run it with psql against the v4 target,',
    '-- only after `status` reports ready-for-cutover, and only after you have read every line and every result.',
    '-- It ends in ROLLBACK. Change that last line to COMMIT when the results are what you expect.',
    '-- Keep this file private (it holds memory content) and delete it after the restore.',
    '',
    'BEGIN;',
    'SET LOCAL standard_conforming_strings = on;',
    '',
  ];
  if (notRestored.length > 0) {
    out.push(`-- NOT RESTORED by this file (${notRestored.length}): left out because the value could not be written with certainty. They stay in set-aside.json.`);
    for (const item of notRestored) out.push(`--   ${item.section}: key ${JSON.stringify(item.key).replaceAll('\n', ' ')}: ${item.reason}`);
    out.push('');
  }

  if (sits.length > 0) {
    out.push(
      '-- observation_sits: kept with their own ids; a sit whose observation is not in v4 has no home and is listed below.',
      'CREATE TEMP TABLE restore_sits (id integer, observation_id integer, sit_note text, sat_at timestamptz) ON COMMIT DROP;',
      `INSERT INTO restore_sits VALUES\n${valuesBlock(sits)};`,
      'SELECT count(*) AS existing_observation_sits FROM observation_sits;  -- expect 0: the migration creates none',
      'INSERT INTO observation_sits (id, observation_id, sit_note, sat_at)',
      'SELECT r.id, r.observation_id, r.sit_note, r.sat_at FROM restore_sits r',
      'WHERE EXISTS (SELECT 1 FROM observations o WHERE o.id = r.observation_id) ORDER BY r.id;',
      'SELECT r.id AS sit_without_a_home FROM restore_sits r WHERE NOT EXISTS (SELECT 1 FROM observations o WHERE o.id = r.observation_id);',
      "SELECT setval(pg_get_serial_sequence('observation_sits', 'id'), COALESCE((SELECT max(id) FROM observation_sits), 1), (SELECT count(*) > 0 FROM observation_sits));",
      '',
    );
  }
  if (lastSat.length > 0) {
    out.push(
      '-- observations.last_sat_at: only where v4 has none.',
      'CREATE TEMP TABLE restore_last_sat (id integer, last_sat_at timestamptz) ON COMMIT DROP;',
      `INSERT INTO restore_last_sat VALUES\n${valuesBlock(lastSat)};`,
      'UPDATE observations o SET last_sat_at = r.last_sat_at FROM restore_last_sat r WHERE o.id = r.id AND o.last_sat_at IS NULL;',
      'SELECT r.id AS observation_without_a_home FROM restore_last_sat r WHERE NOT EXISTS (SELECT 1 FROM observations o WHERE o.id = r.id);',
      '',
    );
  }
  if (images.length > 0) {
    out.push(
      '-- images. A NULL below means the source had no value; it leaves the image as it is.',
      'CREATE TEMP TABLE restore_images (id integer, charge text, view_count integer, last_viewed_at timestamptz) ON COMMIT DROP;',
      `INSERT INTO restore_images VALUES\n${valuesBlock(images)};`,
      '',
      '-- READ THIS RESULT FIRST. v4 already holds v3.2\'s access data in view_count and last_viewed_at. These images have',
      '-- data in v4, so they KEEP it: their set-aside view_count and last_viewed_at (shown here) are NOT restored.',
      'SELECT i.id, i.view_count AS v4_view_count, i.last_viewed_at AS v4_last_viewed_at, r.view_count AS set_aside_view_count, r.last_viewed_at AS set_aside_last_viewed_at',
      'FROM images i JOIN restore_images r ON r.id = i.id',
      'WHERE (r.view_count IS NOT NULL OR r.last_viewed_at IS NOT NULL) AND (i.view_count <> 0 OR i.last_viewed_at IS NOT NULL) ORDER BY i.id;',
      '',
      '-- charge: the migration carries none from v3.2, so v4 holds only the default.',
      'UPDATE images i SET charge = r.charge FROM restore_images r WHERE i.id = r.id AND r.charge IS NOT NULL;',
      '-- view_count and last_viewed_at: only where v4 still has the defaults (view_count = 0 and last_viewed_at IS NULL).',
      'UPDATE images i SET view_count = COALESCE(r.view_count, i.view_count), last_viewed_at = COALESCE(r.last_viewed_at, i.last_viewed_at)',
      'FROM restore_images r WHERE i.id = r.id AND (i.view_count = 0 OR i.view_count IS NULL) AND i.last_viewed_at IS NULL;',
      'SELECT r.id AS image_without_a_home FROM restore_images r WHERE NOT EXISTS (SELECT 1 FROM images i WHERE i.id = r.id);',
      '',
    );
  }
  out.push('ROLLBACK;  -- change to COMMIT; once you have read the results above', '');
  return { sql: out.join('\n'), counts, not_restored: notRestored };
}
